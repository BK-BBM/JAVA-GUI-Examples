    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        // TODO add your handling code here:
        String username = "Admin";
        //String password = "Admin@1";//THIS WILL NOT WORK
        char[] password = "Admin@1".toCharArray();
        
        /* A password is a string of characters 
         and therefore will not work when we make it a string.
        Instead we can try making it a char or char[]
        */
        
        if(txtUsername.getText().equals(username)
                && Arrays.equals(txtPassword.getPassword(), password))
        {
            JOptionPane.showMessageDialog(rootPane,
                    "Login Successful\n" + "Welcome back: " + username);
            
            Dashboard dashboard = new Dashboard();
            dashboard.setVisible(true);
            
            this.dispose();
        }
        else{
            JOptionPane.showMessageDialog(rootPane, 
                    "Username and password combination is incorrect."
                            + "\nPlease try again");
        }
    }//GEN-LAST:event_btnLoginActionPerformed

