    private void initPanel(){
        /* We're only doing this because Dashboard already inherits from JFrame 
         and we can't inherit JPanel in this class.
      
         Much easier than creating a new class that inherits from JPanel
        */
        
         cardLayout = new java.awt.CardLayout();
         panel.setLayout(cardLayout);
         
         /*create new instances of JPanel 
          because we want our app to switch screens 
         depending on the menu item clicked
         */
         
         JPanel file = new JPanel();
         file.setBackground(Color.RED);
         JPanel edit = new JPanel();
         edit.setBackground(Color.GREEN);
         JPanel write = new JPanel();
         write.setBackground(Color.BLUE);
         JPanel read = new JPanel();
         read.setBackground(Color.PINK);
         
         /*register these instances to our main panel (on the view) so that
          we can switch between each panel
         */
         
        
         panel.add(file,"FILE");
         panel.add(edit,"EDIT");
         panel.add(write,"WRITE");
         panel.add(read, "READ");
         
       
         
        
    }
