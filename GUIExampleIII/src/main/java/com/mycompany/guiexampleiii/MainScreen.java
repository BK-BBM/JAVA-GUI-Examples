    private void btnSubmitFormActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSubmitFormActionPerformed
        // TODO add your handling code here:
        String name = txtName.getText();
        String surname = txtSurname.getText();
        String isFun = "";
        
        if(chckYes.isSelected() == true)
        {
            isFun = "Yes";
        }
        else if(chckDoubleYes.isSelected() == true)
        {
            isFun = "The best";
        }
        JOptionPane.showMessageDialog(homePanel,
        
          "Hi " +name + " " + surname +"\n"
           +"Is Programming fun? ->Your answer: "+ isFun);
        
       
        
        
    }//GEN-LAST:event_btnSubmitFormActionPerformed

